-- mynet 网络与日志统一配置文件（由 mynet::reloadConfig("config.lua") 动态热加载）
--
-- 安全机制说明：
-- 1. 脚本在严格沙箱化的裸 lua_State 中执行，io / os / package / debug 等标准库完全被禁用，
--    杜绝恶意脚本调用外部命令或进行未授权文件系统篡改；
-- 2. 设置单次执行最多 50,000,000 条指令配额，阻断由于死循环带来的拒绝服务 (DoS) 风险；
-- 3. 事务性全量校验 (All-or-Nothing)：仅当所有配置项与字段语法完全合法时才原子发布更新，
--    解析中途发生任何错误将自动回滚，保留当前在线运行参数不变；
-- 4. 字段值超出安全运行边界时会自动进行边界安全钳位 (Clamping)。

-- -----------------------------------------------------------------------------
-- 1. 服务端传输与连接层配置
-- -----------------------------------------------------------------------------
server = {
    -- 监听绑定的 IP 地址
    host = "0.0.0.0",

    -- 监听端口号（合法区间 [1, 65535]）
    port = 8888,

    -- TCP 监听队列最大等待握手连接数
    backlog = 128,

    -- 服务端允许维持的最大活跃连接数上限
    maxConnections = 65536,

    -- 长连接空闲超时时间（毫秒，合法区间 [100, 86400000] 即最长 24 小时）
    keepAliveTimeout_ms = 60000, -- 60 秒

    -- 单个连接发送缓冲区写高水位线（字节，触发背压暂停对端读取）
    writeHighWaterMark = 4 << 20, -- 4 MiB

    -- 单个连接最大允许累积未消费的请求数据量（字节，超额触发解析错误并关闭）
    maxRequestBytes = 4 << 20, -- 4 MiB

    -- 是否开启 TCP_NODELAY 禁用 Nagle 算法（减少小包延迟）
    tcpNoDelay = true,

    -- 是否开启 TCP_QUICKACK 快速确认
    tcpQuickAck = false,

    -- 是否启用 Linux splice 内核零拷贝通道（明文 TCP Echo 自动环回）
    enableSplice = true
}

-- -----------------------------------------------------------------------------
-- 2. io_uring Proactor 异步完成态引擎配置
-- -----------------------------------------------------------------------------
proactor = {
    -- io_uring 提交队列深度 (Submission Queue Entries)
    sqEntries = 2048,

    -- 内核缓冲环槽位数量 (Buffer Ring Entries)
    bufEntries = 1024,

    -- 内核缓冲环每个槽位内存大小（字节，推荐 4096 契合页面大小）
    bufSize = 4096
}

-- -----------------------------------------------------------------------------
-- 3. HTTP/2 多路复用器流并发与流控配置
-- -----------------------------------------------------------------------------
multiplexer = {
    -- 单连接最大并发多路复用活跃流数量
    maxConcurrentStreams = 100,

    -- 初始流控窗口大小（字节，HTTP/2 默认 65535）
    initialWindowSize = 65535,

    -- 单帧 Payload 最大字节上限（合法区间 [16384, 16777215]）
    maxFrameSize = 16384,

    -- 首部解压缩最大字节上限
    maxHeaderListSize = 8192
}

-- -----------------------------------------------------------------------------
-- 4. TLS 加密传输配置
-- -----------------------------------------------------------------------------
security = {
    -- 是否开启 TLS 加密传输
    enableTls = false,

    -- 服务端证书文件路径 (.crt / .pem)
    certFile = "server.crt",

    -- 服务端私钥文件路径 (.key / .pem)
    keyFile = "server.key",

    -- CA 根证书路径（双向认证时使用）
    caFile = "",

    -- 加密密码套件配置
    ciphers = "DEFAULT",

    -- ALPN 协议协商列表（逗号分隔）
    alpnProtocols = "h2,http/1.1"
}

-- -----------------------------------------------------------------------------
-- 5. mylog 诊断日志子系统联合配置（热加载时自动同步生效）
-- -----------------------------------------------------------------------------
logger = {
    -- 最低日志输出级别："trace" | "debug" | "info" | "warn" | "error" | "fatal"
    suppressLevel = "info",

    -- 终端是否输出鲜艳 ANSI 彩色
    stdoutVivid = true,

    -- 是否转义控制字符以防日志注入伪造
    escapeControlChars = true,

    -- 时间戳采用 UTC 还是本地时间
    timestampUtc = false,

    -- 单条日志最大字符长度
    maxLogLength = 4096,

    -- 遇到 FATAL 日志后的动作："none" | "exit" | "abort"
    fatalAction = "none"
}

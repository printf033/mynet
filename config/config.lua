-- mynet 网络与日志统一配置文件（由 mynet::reloadConfig("config.lua") 动态热加载）
--
-- 安全机制说明：
-- 1. 脚本在严格沙箱化的裸 lua_State 中执行，io / os / package / debug 等标准库完全被禁用，
--    杜绝恶意脚本调用外部命令或进行未授权文件系统篡改；
-- 2. 设置单次执行最多 50,000,000 条指令配额，阻断由于死循环带来的拒绝服务 (DoS) 风险；
-- 3. 事务性全量校验 (All-or-Nothing)：仅当所有配置项与字段语法完全合法时才原子发布更新，
--    解析中途发生任何错误将自动回滚，保留当前在线运行参数不变；
-- 4. 字段值超出安全运行边界时会自动进行边界安全钳位 (Clamping)。

-- -----------------------------------------------------------------------------
-- 生效时机说明（与 src/configHolder.hpp 的 kConfigReloadMap 一一对应）
--
--   [热]   运行中 reloadConfig() 后立即生效：每个新连接或每次 I/O 都会重新读取。
--   [启动] 引擎/监听器启动时读取一次；reload 后必须重启该服务才生效。
--
-- 判断标准是"读它的代码在哪"：被 Connection/Datagram/Handler 在每连接路径上读的
-- 就是 [热]；只在 listen()/serve()/runSsl() 里读一次的就是 [启动]。
-- 没有任何字段是"配了但不读"的——tests/test_config_lua.cpp 会核对这一点。
-- -----------------------------------------------------------------------------

-- -----------------------------------------------------------------------------
-- 1. 服务端传输与连接层配置
-- -----------------------------------------------------------------------------
server = {
    -- 监听绑定的 IP 地址 [启动]
    host = "0.0.0.0",

    -- 监听端口号（合法区间 [1, 65535]）[启动]
    port = 8888,

    -- TCP 监听队列最大等待握手连接数（合法区间 [1, 65535]）[启动]
    backlog = 128,

    -- 连接上限，同时也是引擎的池容量（合法区间 [1, 1000000]）[启动]
    -- Reactor 用它做连接池槽位数，Proactor 用它做会话池槽位数——唯一真源。
    --
    -- 这是启动时**预分配**的槽位数量，不是按需增长的上限。每个槽位连同其请求/
    -- 响应缓冲区实测约 3 KiB，因此：8192 ≈ 24 MiB，65536 ≈ 190 MiB。
    -- 按实际并发量设置，而不是照抄一个"看起来很大"的数字。
    maxConnections = 8192,

    -- 引擎侧空闲连接回收超时（秒，合法区间 [0, 86400]，0 表示禁用）[启动]
    idleTimeoutSecs = 0,

    -- 扫描节拍见 reactor.idleSweepIntervalMs / proactor.cqeWaitMs。

    -- 是否开启 TCP_NODELAY 禁用 Nagle 算法（减少小包延迟）[热]
    tcpNoDelay = true,

    -- 是否开启 TCP_QUICKACK 快速确认 [热]
    tcpQuickAck = false,

    -- 是否启用 Linux splice 内核零拷贝通道（明文 TCP Echo 自动环回）[热]
    enableSplice = true
}

-- -----------------------------------------------------------------------------
-- 2. epoll Reactor 引擎运行参数
-- -----------------------------------------------------------------------------
reactor = {
    -- 单次 epoll_wait 最大返回事件数（个，合法区间 [16, 65536]）[启动]
    maxEvents = 1024,

    -- 空闲连接扫描节拍（毫秒，合法区间 [10, 60000]）[启动]
    -- 只影响"多久检查一次谁超时"，超时本身是 server.idleTimeoutSecs。
    -- 越小越精确、开销越大；设为超时值的 1/10 左右是常见选择。
    idleSweepIntervalMs = 1000
}

-- -----------------------------------------------------------------------------
-- 3. 流式连接与请求响应管道配置（全部 [热]）
-- -----------------------------------------------------------------------------
connection = {
    -- 默认响应队列初始槽位容量 (条，允许单连接并发流水线处理的响应数量，合法区间 [1, 65536])
    responseCapacity = 64,

    -- 单次直写请求接收读取分块大小 (字节，合法区间 [256, 16777216])
    readChunkSize = 4096, -- 4 KiB

    -- 单连接最大允许累积未消费的请求数据量 (字节，超额触发解析错误并关闭，合法区间 [1024, 1073741824])
    maxRequestBytes = 4 * 1024 * 1024, -- 4 MiB

    -- 单连接发送队列高水位线 (字节，超出触发背压暂停对端读取，合法区间 [1024, 1073741824])
    writeHighWaterMark = 4 * 1024 * 1024, -- 4 MiB

    -- 发送积压硬顶倍数（当 pendingBytes >= writeHardCapFactor * writeHighWaterMark 时触发发完即关保护，合法区间 [1, 64]）
    writeHardCapFactor = 2,

    -- Linux splice(2) 内核零拷贝单次管道搬移分块大小 (字节，合法区间 [1024, 16777216])
    spliceChunkSize = 64 * 1024, -- 64 KiB

    -- 向量化写操作 (writev/sendmsg) 单次系统调用最大聚合分片数 (合法区间 [1, 64])
    maxWriteIov = 16
}

-- -----------------------------------------------------------------------------
-- 4. UDP 数据报会话与回复队列配置（全部 [热]）
-- -----------------------------------------------------------------------------
datagram = {
    -- 单个 UDP 数据报载荷上限 (字节，合法区间 [512, 65535])
    maxDatagramBytes = 65535,

    -- 单个处理器外发队列积压报文条数上限 (条，合法区间 [16, 65536])
    maxPendingOutgoing = 1024
}

-- -----------------------------------------------------------------------------
-- 5. io_uring Proactor 异步完成态引擎配置（全部 [启动]）
-- -----------------------------------------------------------------------------
proactor = {
    -- io_uring 提交队列深度 (Submission Queue Entries，合法区间 [64, 32768])
    sqEntries = 2048,

    -- io_uring 完成队列深度 (Completion Queue Entries，合法区间 [64, 32768])
    -- 硬性约束：cqEntries 必须 >= sqEntries（内核对 IORING_SETUP_CQSIZE 的要求，
    -- 违反会让 io_uring_queue_init_params() 返回 EINVAL）；小于时自动抬升到 sqEntries。
    cqEntries = 2048,

    -- 在途 multishot accept 并发上限（个，合法区间 [1, 4096]）
    maxAcceptEvents = 256,

    -- 内核缓冲环槽位数量 (Buffer Ring Entries，合法区间 [16, 65536])
    bufEntries = 1024,

    -- 内核缓冲环每个槽位内存大小（字节，推荐 4096 契合页面大小，合法区间 [512, 1048576]）
    bufSize = 4096,

    -- UDP 接收窗口下限（字节；实际窗口取它与处理器报文上界的较大者，合法区间 [512, 1048576]）
    udpBufSize = 64 * 1024,

    -- Buffer Ring 底层内存对齐粒度（字节，必须是 2 的幂，合法区间 [8, 1048576]）
    -- posix_memalign 的硬性要求；非 2 的幂会被拒绝并回退到当前值。
    bufRingAlignment = 4096,

    -- 等待完成事件的超时上限（毫秒，合法区间 [1, 60000]）
    -- 超时后才会扫描空闲会话、投递取消批次并重新提交，属于事件循环轮转节拍。
    cqeWaitMs = 1000
}

-- -----------------------------------------------------------------------------
-- 6. HTTP/2 多路复用器流并发与流控配置（全部 [热]）
-- -----------------------------------------------------------------------------
multiplexer = {
    -- 单连接最大并发多路复用活跃流数量（合法区间 [1, 10000]）
    maxConcurrentStreams = 100,

    -- 连接级与流级初始流控窗口大小（字节，HTTP/2 默认 65535，合法区间 [1024, 2147483647]）
    initialWindowSize = 65535,

    -- 本端接受的单帧 Payload 上限（合法区间 [16384, 16777215]）
    maxFrameSize = 16384
}

-- -----------------------------------------------------------------------------
-- 7. TLS 加密传输配置（全部 [启动]）
-- -----------------------------------------------------------------------------
security = {
    -- 服务端证书文件路径 (.crt / .pem)。
    -- runSsl(ip, port) 无路径重载从这两项读取；runSsl(ip, port, crt, key) 可显式覆盖。
    -- 默认留空：库的编译期基线不假设某个证书文件存在，部署时按实际路径填写。
    -- 仓库自带示例证书为 "../certs/ser.crt" / "../certs/ser.key"。
    certFile = "",

    -- 服务端私钥文件路径 (.key / .pem)，同上。
    keyFile = "",

    -- CA 根证书路径（双向认证时使用；留空表示不加载自定义 CA）
    caFile = "",

    -- 加密密码套件配置（TLS 1.2 及以下）。
    -- 留空 = 不调用 SSL_CTX_set_cipher_list，保留 OpenSSL 从 openssl.cnf 读到的
    -- system_default 策略（加固部署的套件限制因此继续生效）。
    -- 显式写 "DEFAULT" 会被归一为同样的"不调用"，不会覆盖系统策略。
    ciphers = "",

    -- ALPN 协议协商列表（逗号分隔）。
    -- 默认留空 = 不协商 ALPN，与引入配置驱动之前的行为一致：没实现 h2 的服务端
    -- 不应该对客户端宣告 h2。确实实现了对应协议时再填入，例如 "h2,http/1.1"。
    alpnProtocols = ""
}

-- -----------------------------------------------------------------------------
-- 8. mylog 诊断日志子系统联合配置（热加载时自动同步生效）
-- -----------------------------------------------------------------------------
logger = {
    -- 最低日志输出级别："trace" | "debug" | "info" | "warn" | "error" | "fatal"
    suppressLevel = "info",

    -- 终端是否输出鲜艳 ANSI 彩色
    stdoutVivid = true,

    -- 是否转义控制字符以防日志注入伪造
    escapeControlChars = true,

